import { viewerUrl } from './locator.js';

function label(value: string): string {
  return value.replace(/[&<>]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]!)).replace(/[\\`*_{}\[\]()!#|]/g, '\\$&');
}
function localLink(value: string): string { return './' + encodeURIComponent(value).replace(/[!'()*]/g, c => '%' + c.charCodeAt(0).toString(16)); }

export function landingPage(opts: { name: string; ciphertextFile: string; repo: string; viewer: string; qrFile: string; ref?: string }): string {
  const url = viewerUrl(opts.viewer, opts.repo, opts.ciphertextFile, opts.ref);
  return [
    '<!-- Generated by GitVault. This is a public landing page, not the private document. -->',
    '# This document is encrypted',
    '',
    '**' + label(opts.name) + '** lives in a public repository. Its contents do not.',
    '',
    '### [Open in GitVault](' + url + ')',
    '',
    'Open the viewer and use the unlock method configured for this file: password, private age identity, or a supported encryption passkey. Not every method works for every file.',
    '',
    'Or scan to open the viewer **on your phone**:',
    '',
    '![QR code linking to the GitVault viewer](' + localLink(opts.qrFile) + ')',
    '',
    '> The link and QR code contain **no password or decryption key**. Scanning opens the viewer; it does not grant access. Check the viewer address before entering a secret.',
    '',
    '[Download encrypted .age file](' + localLink(opts.ciphertextFile.split('/').at(-1)!) + ')',
    '',
    'Decryption happens on your device. GitHub still exposes filenames, sizes and history. GitVault is an unaudited prototype.',
    '',
  ].join('\n');
}
